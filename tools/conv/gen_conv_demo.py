#!/usr/bin/env python3
"""Emit the captured conv-simple self-test ROM for the first conv board image.

Contents are taken verbatim from the frozen fixture
``tests/conv/fixtures/conv_simple_fp16_3x3_c4_h8_w8_oc16``:

* the 52-QWORD command stream with only QWORDs 18/24/32 retargeted to this
  image's BRAM windows,
* the packed input and weight BOs byte for byte,
* the captured output BO bytes as the comparison oracle.

Nothing is synthesised numerically, and the generator refuses to run if the
fixture manifest hashes do not match.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
CASE = 'conv_simple_fp16_3x3_c4_h8_w8_oc16'
FIXTURE = ROOT / 'tests/conv/fixtures' / CASE
BASE = 0x10000000
COMMAND_BASE = BASE + 0x0000
INPUT_BASE = BASE + 0x1000
WEIGHT_BASE = BASE + 0x2000
OUTPUT_BASE = BASE + 0x3000
COMMAND_WORDS = 52
INPUT_HALFWORDS = 256
WEIGHT_HALFWORDS = 1152
OUTPUT_HALFWORDS = 576
TARGET = ROOT / 'rtl/cmac/rk_conv_simple_demo_rom.sv'
FIXTURE_OUT = ROOT / 'tests/conv_simple_demo_fixture.json'


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load() -> tuple[list[int], list[int], list[int], list[int]]:
    manifest = json.loads((FIXTURE / 'manifest.json').read_text())
    if manifest['case'] != CASE:
        raise SystemExit('fixture identity mismatch')
    for name, record in manifest['files'].items():
        path = FIXTURE / name
        if path.stat().st_size != record['bytes'] or sha(path) != record['sha256']:
            raise SystemExit(f'fixture file changed: {name}')
    if manifest['command_stream']['qwords'] != COMMAND_WORDS:
        raise SystemExit('command length changed')
    if manifest['command_stream']['address_qwords'] != [18, 24, 32]:
        raise SystemExit('relocation set changed')
    raw = bytearray((FIXTURE / 'regcmd.bin').read_bytes())
    if len(raw) != COMMAND_WORDS * 8:
        raise SystemExit('command stream is not 52 QWORDs')
    for index, address in ((18, INPUT_BASE), (24, WEIGHT_BASE), (32, OUTPUT_BASE)):
        offset = index * 8
        raw[offset + 2:offset + 6] = address.to_bytes(4, 'little')
    command = list(struct.unpack(f'<{COMMAND_WORDS}Q', bytes(raw)))

    def halfwords(name: str, count: int) -> list[int]:
        payload = (FIXTURE / name).read_bytes()
        if len(payload) != count * 2:
            raise SystemExit(f'{name}: expected {count} halfwords, got {len(payload) // 2}')
        return list(struct.unpack(f'<{count}H', payload))

    inputs = halfwords('input.bin', INPUT_HALFWORDS)
    weights = halfwords('weight.bin', WEIGHT_HALFWORDS)
    expected = halfwords('device_out.bin', OUTPUT_HALFWORDS)
    return command, inputs, weights, expected


def render(command: list[int], inputs: list[int], weights: list[int],
           expected: list[int]) -> str:
    text = '''// SPDX-License-Identifier: MIT
`timescale 1ns/1ps
// Generated by tools/conv/gen_conv_demo.py from the frozen conv-simple
// capture. Do not edit by hand; run the generator instead.
module rk_conv_simple_demo_rom (
    input  logic [5:0]  command_index,
    output logic [63:0] command_data,
    input  logic [7:0]  input_index,
    output logic [15:0] input_data,
    input  logic [10:0] weight_index,
    output logic [15:0] weight_data,
    input  logic [9:0]  expected_index,
    output logic [15:0] expected_data,
    output logic [31:0] command_base, input_base, weight_base, output_base,
    output logic [31:0] start_amount
);
    assign command_base = 32'h%08x;
    assign input_base = 32'h%08x;
    assign weight_base = 32'h%08x;
    assign output_base = 32'h%08x;
    assign start_amount = 32'd%d;
    always_comb begin
        command_data = 64'd0;
        case (command_index)
''' % (COMMAND_BASE, INPUT_BASE, WEIGHT_BASE, OUTPUT_BASE, COMMAND_WORDS)
    for index, word in enumerate(command):
        text += f"            6'd{index}: command_data = 64'h{word:016x};\n"
    text += '''            default: begin end
        endcase
    end
    always_comb begin
        input_data = 16'd0;
        case (input_index)
'''
    for index, value in enumerate(inputs):
        text += f"            8'd{index}: input_data = 16'h{value:04x};\n"
    text += '''            default: begin end
        endcase
    end
    always_comb begin
        weight_data = 16'd0;
        case (weight_index)
'''
    for index, value in enumerate(weights):
        text += f"            11'd{index}: weight_data = 16'h{value:04x};\n"
    text += '''            default: begin end
        endcase
    end
    always_comb begin
        expected_data = 16'd0;
        case (expected_index)
'''
    for index, value in enumerate(expected):
        text += f"            10'd{index}: expected_data = 16'h{value:04x};\n"
    text += '''            default: begin end
        endcase
    end
endmodule
'''
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    command, inputs, weights, expected = load()
    source = render(command, inputs, weights, expected)
    record = {
        'case': CASE,
        'description': 'Captured conv-simple C4 8x8 -> OC16 k3x3 self-test image data.',
        'command_words': len(command),
        'command_sha256': hashlib.sha256(
            b''.join(struct.pack('<Q', w) for w in command)).hexdigest(),
        'input_halfwords': len(inputs),
        'weight_halfwords': len(weights),
        'expected_halfwords': len(expected),
        'command_base': COMMAND_BASE,
        'input_base': INPUT_BASE,
        'weight_base': WEIGHT_BASE,
        'output_base': OUTPUT_BASE,
    }
    outputs = {TARGET: source,
               FIXTURE_OUT: json.dumps(record, indent=2, sort_keys=True) + '\n'}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Generated file is stale: {path}')
        else:
            path.write_text(content)
    print('Conv-simple demo ROM matches the frozen capture.' if args.check
          else 'Generated captured conv-simple demo ROM.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
