#!/usr/bin/env python3
"""Generate the strict per-capture conv-simple register tables.

Every row is the exact 52-QWORD stream of a frozen ``conv-simple`` fixture.
Only the three job-declared DMA address words (18, 24, 32) are relocatable;
their value fields are zeroed here and supplied at run time, so the table
stays independent of any particular BO placement.

Usage:
    python3 tools/conv/gen_conv_simple_profiles.py
    python3 tools/conv/gen_conv_simple_profiles.py --check
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / 'tests/conv/fixtures'
OUTPUT = ROOT / 'rtl/cmac/rk_conv_simple_profiles.svh'

# Every frozen conv-simple capture whose RTL output path exists. The FP32 row
# selects the NCHW transposing writer in `rk_conv_simple_core`; its expected
# output BO is the logical [C][H][W] FP32 tensor, which is exactly what the
# device captured.
PROFILES = (
    {'id': 0, 'name': 'FP16_3X3_C4_OC16',
     'case': 'conv_simple_fp16_3x3_c4_h8_w8_oc16',
     'input_bytes': 512, 'weight_bytes': 2304, 'output_bytes': 1152},
    {'id': 1, 'name': 'FP16_5X5_C4_OC16',
     'case': 'conv_simple_fp16_5x5_c4_h8_w8_oc16',
     'input_bytes': 512, 'weight_bytes': 6400, 'output_bytes': 512},
    {'id': 2, 'name': 'FP16_3X3_C16_OC32',
     'case': 'conv_simple_fp16_3x3_c16_h8_w8_oc32',
     'input_bytes': 2048, 'weight_bytes': 9216, 'output_bytes': 2304},
    # fetch_words 52 with one padding word: the last real command is word 50.
    {'id': 3, 'name': 'FP32_1X1_C4_OC16',
     'case': 'conv_simple_fp16_1x1_c4_h8_w8_oc16',
     'input_bytes': 512, 'weight_bytes': 256, 'output_bytes': 4096},
)
ADDRESS_WORDS = (18, 24, 32)
WORDS = 52


def load(case: str) -> list[int]:
    fixture = FIXTURES / case
    manifest = json.loads((fixture / 'manifest.json').read_text())
    raw = (fixture / 'regcmd.bin').read_bytes()
    if len(raw) != WORDS * 8:
        raise ValueError(f'{case}: expected {WORDS} QWORDs, got {len(raw) // 8}')
    if manifest['command_stream']['address_qwords'] != list(ADDRESS_WORDS):
        raise ValueError(f'{case}: unexpected relocation set')
    qwords = list(struct.unpack(f'<{WORDS}Q', raw))
    if qwords[-1] != 0:
        raise ValueError(f'{case}: final padding QWORD is not zero')
    for index in ADDRESS_WORDS:
        qwords[index] &= ~(0xffffffff << 16)
    return qwords


def emitted() -> str:
    tables = [(profile, load(profile['case'])) for profile in PROFILES]
    lines = [
        '// SPDX-License-Identifier: MIT',
        '// GENERATED by tools/conv/gen_conv_simple_profiles.py. Do not edit.',
        "// Each row is one frozen conv-simple capture's exact 52-QWORD stream.",
        '// QWORDs 18, 24 and 32 are the job-declared input/weight/output',
        '// addresses: their value field is zeroed here and supplied by the',
        '// command stream at run time.',
        '//',
        '// Profile ids:',
    ]
    for profile, _ in tables:
        lines.append(f'//   {profile["id"]}: {profile["name"]} ({profile["case"]})')
    lines.append('')
    for profile, _ in tables:
        lines.append(f'localparam int unsigned CONV_SIMPLE_{profile["name"]} = {profile["id"]};')
    lines.append('')
    lines.append('// True when the index is one of the three job-declared buffer')
    lines.append('// address words. Its value field is a relocation, not a constant.')
    lines.append('function automatic logic conv_simple_address_word(')
    lines.append('    input logic [5:0] index')
    lines.append(');')
    lines.append('    conv_simple_address_word = ' +
                 ' || '.join(f'index == 6\'d{i}' for i in ADDRESS_WORDS) + ';')
    lines.append('endfunction')
    lines.append('')
    lines.append('function automatic logic [63:0] conv_simple_template_word(')
    lines.append('    input int unsigned profile,')
    lines.append('    input logic [5:0] index')
    lines.append(');')
    lines.append('    case (profile)')
    for profile, table in tables:
        lines.append(f'        {profile["id"]}: case (index)')
        for index, word in enumerate(table):
            lines.append(f'            {index}: conv_simple_template_word = 64\'h{word:016x};')
        lines.append('            default: conv_simple_template_word = 64\'h0;')
        lines.append('        endcase')
    lines.append('        default: conv_simple_template_word = 64\'h0;')
    lines.append('    endcase')
    lines.append('endfunction')
    lines.append('')
    lines.append('// BO byte sizes declared by each capture; the endpoint publishes')
    lines.append('// these instead of inferring geometry from the command fields.')
    lines.append('function automatic logic [31:0] conv_simple_input_bytes(')
    lines.append('    input int unsigned profile);')
    lines.append('    case (profile)')
    for profile, _ in tables:
        lines.append(f'        {profile["id"]}: conv_simple_input_bytes = 32\'d{profile["input_bytes"]};')
    lines.append('        default: conv_simple_input_bytes = 32\'d0;')
    lines.append('    endcase')
    lines.append('endfunction')
    lines.append('')
    lines.append('function automatic logic [31:0] conv_simple_weight_bytes(')
    lines.append('    input int unsigned profile);')
    lines.append('    case (profile)')
    for profile, _ in tables:
        lines.append(f'        {profile["id"]}: conv_simple_weight_bytes = 32\'d{profile["weight_bytes"]};')
    lines.append('        default: conv_simple_weight_bytes = 32\'d0;')
    lines.append('    endcase')
    lines.append('endfunction')
    lines.append('')
    lines.append('function automatic logic [31:0] conv_simple_output_bytes(')
    lines.append('    input int unsigned profile);')
    lines.append('    case (profile)')
    for profile, _ in tables:
        lines.append(f'        {profile["id"]}: conv_simple_output_bytes = 32\'d{profile["output_bytes"]};')
    lines.append('        default: conv_simple_output_bytes = 32\'d0;')
    lines.append('    endcase')
    lines.append('endfunction')
    lines.append('')
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = emitted()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f'{OUTPUT} is stale; run tools/conv/gen_conv_simple_profiles.py',
                  file=sys.stderr)
            return 1
        print(f'{OUTPUT.relative_to(ROOT)} is current '
              f'({len(PROFILES)} exact conv-simple profiles)')
        return 0
    OUTPUT.write_text(text)
    print(f'wrote {OUTPUT.relative_to(ROOT)} ({len(PROFILES)} profiles, '
          f'{hashlib.sha256(text.encode()).hexdigest()[:16]})')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
