#!/usr/bin/env python3
"""Generate the strict per-capture convolution register tables.

Every table is derived from a pinned fixture's own relocated 54-QWORD stream;
no register value is hand-written here. Adding a capture means adding a
registry row, re-running this tool, and rerunning the contract tests.

Usage:
    python3 tools/conv/gen_conv_profiles.py           # write the header
    python3 tools/conv/gen_conv_profiles.py --check    # verify it is current
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
FIXTURES = ROOT / 'tests/conv/fixtures'
OUTPUT = ROOT / 'rtl/cmac/rk_conv_3x3_profiles.svh'

# Profile id -> (fixture case, address relocation map, BO sizes in bytes).
# The address map is the fixture runner's canonical placement, so the emitted
# table is exactly what the replay feeds to the raw endpoint.
PROFILES = (
    {'id': 0, 'name': 'VALID', 'case': 'conv_3x3_valid_c4_h9_w9_oc4',
     'addresses': {'a': 0x1000, 'w': 0x2000, 'out': 0x3000}},
    {'id': 1, 'name': 'STRIDE2', 'case': 'conv_3x3_stride2_c4_h11_w11_oc4',
     'addresses': {'a': 0x1000, 'w': 0x2000, 'out': 0x3000}},
    {'id': 2, 'name': 'PAD1_ZERO_FRAME',
     'case': 'conv_3x3_pad1_zero_frame_c4_h9_w9_oc4',
     'addresses': {'a': 0x1000, 'w': 0x2000, 'out': 0x3000}},
    {'id': 3, 'name': 'GROUPED_C2',
     'case': 'conv_grouped_3x3_c4_h5_w5_oc8_g2_task0',
     'addresses': {'a': 0x1000, 'w': 0x2000, 'out': 0x3000}},
    {'id': 4, 'name': 'GROUPED_C2_TASK1',
     'case': 'conv_grouped_3x3_c4_h5_w5_oc8_g2_task1',
     'addresses': {'a': 0x1000, 'w': 0x2000, 'out': 0x3000}},
    {'id': 5, 'name': 'SPLIT_OC_C16',
     'case': 'conv_splitoc_3x3_c16_h9_w9_oc16_task0',
     'addresses': {'a': 0x1000, 'w': 0x2000, 'out': 0x3000}},
    {'id': 6, 'name': 'SPLIT_OC_C16_TASK1',
     'case': 'conv_splitoc_3x3_c16_h9_w9_oc16_task1',
     'addresses': {'a': 0x1000, 'w': 0x2000, 'out': 0x3000}},
    {'id': 7, 'name': 'DEPTHWISE_C3',
     'case': 'conv_depthwise_3x3_c3_h11_w28_oc3',
     'addresses': {'a': 0x1000, 'w': 0x3000, 'out': 0x4000}},
    # The depthwise fixture relocates weights/output at 0x3000/0x4000 to
    # match the captured job's own placement (the capture mapped them at
    # 12,288 and 16,384 because its allocations were sequential).
)
ADDRESS_WORDS = (21, 27, 35)
WORDS = 54


def relocate(case: str, addresses: dict[str, int]) -> bytes:
    fixture = FIXTURES / case
    job = json.loads((fixture / 'job.json').read_text())
    raw = (fixture / 'regcmd.bin').read_bytes()
    if len(raw) != WORDS * 8:
        raise ValueError(f'{case}: expected 54 QWORDs, got {len(raw) // 8}')
    if [row['regcmd_index'] for row in job['patches']] != list(ADDRESS_WORDS):
        raise ValueError(f'{case}: unexpected relocation set')
    patched = bytearray(raw)
    for patch in job['patches']:
        index = patch['regcmd_index']
        qword, = struct.unpack_from('<Q', patched, index * 8)
        qword = (qword & ~(0xffffffff << 16)) | (addresses[patch['buffer']] << 16)
        struct.pack_into('<Q', patched, index * 8, qword)
    return bytes(patched)


def emitted() -> str:
    tables = []
    for profile in PROFILES:
        payload = relocate(profile['case'], profile['addresses'])
        qwords = list(struct.unpack('<54Q', payload))
        # The three declared relocation words take their value field from the
        # command stream at run time, so the emitted template zeroes it and
        # stays independent of any particular BO placement.
        for index in ADDRESS_WORDS:
            qwords[index] &= ~(0xffffffff << 16)
        table = [f'            64\'h{qword:016x}' for qword in qwords]
        tables.append((profile, table))
    lines = [
        '// SPDX-License-Identifier: MIT',
        '// GENERATED by tools/conv/gen_conv_profiles.py. Do not edit.',
        '// Each row is one pinned capture\'s exact 54-QWORD template. QWORDs 21,',
        '// 27 and 35 are the three job-declared buffer addresses: their value',
        '// field is zeroed here and supplied by the command stream at run time,',
        '// so the table stays independent of any particular BO placement.',
        '//',
        '// Profile ids:',
    ]
    for profile, _ in tables:
        lines.append(f'//   {profile["id"]}: {profile["name"]} ({profile["case"]})')
    lines.append('')
    for profile, table in tables:
        lines.append(f'localparam int unsigned CONV_PROFILE_{profile["name"]} = {profile["id"]};')
    lines.append('')
    lines.append('// True when the index is one of the three job-declared buffer')
    lines.append('// address words. Its value field is a relocation, not a constant.')
    lines.append('function automatic logic conv_profile_address_word(')
    lines.append('    input logic [5:0] index')
    lines.append(');')
    lines.append('    conv_profile_address_word = ' +
                 ' || '.join(f'index == 6\'d{i}' for i in ADDRESS_WORDS) + ';')
    lines.append('endfunction')
    lines.append('')
    lines.append('function automatic logic [63:0] conv_profile_template_word(')
    lines.append('    input int unsigned profile,')
    lines.append('    input logic [5:0] index')
    lines.append(');')
    lines.append('    case (profile)')
    for profile, table in tables:
        lines.append(f'        {profile["id"]}: case (index)')
        for index, word in enumerate(table):
            lines.append(f'            {index}: conv_profile_template_word = {word};')
        lines.append('            default: conv_profile_template_word = 64\'h0;')
        lines.append('        endcase')
    lines.append('        default: conv_profile_template_word = 64\'h0;')
    lines.append('    endcase')
    lines.append('endfunction')
    lines.append('')
    return '\n'.join(lines)


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    text = emitted()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            print(f'{OUTPUT} is stale; run tools/conv/gen_conv_profiles.py',
                  file=sys.stderr)
            return 1
        print(f'{OUTPUT.relative_to(ROOT)} is current '
              f'({len(PROFILES)} exact captured profiles)')
        return 0
    OUTPUT.write_text(text)
    print(f'wrote {OUTPUT.relative_to(ROOT)} ({len(PROFILES)} profiles, '
          f'{hashlib.sha256(text.encode()).hexdigest()[:16]})')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
