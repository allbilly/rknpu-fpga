#!/usr/bin/env python3
"""Emit the captured signed-INT8 pooling self-test ROM for the FPGA bring-up.

The ROM contains only bytes taken from the frozen fixture
(``tests/ppu_pooling/fixtures/int8_max_k2s2_valid_c16_h2w2``):

* the 26-QWORD command stream with its two declared address relocations
  retargeted to this image's BRAM windows,
* the 64-byte input operand actually read by the endpoint,
* the 8-halfword expected output value (the rest of the output BO must remain
  zero).

Nothing is synthesised numerically: the expected bytes are the captured device
bytes. The generator refuses to run if the fixture manifest hashes do not
match, so a stale ROM cannot be emitted silently.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path
import struct
import sys

ROOT = Path(__file__).resolve().parents[2]
FIXTURE = ROOT / 'tests/ppu_pooling/fixtures/int8_max_k2s2_valid_c16_h2w2'
CASE = 'int8_max_k2s2_valid_c16_h2w2'
BASE = 0x10000000
COMMAND_BASE = BASE + 0x000
INPUT_BASE = BASE + 0x200
OUTPUT_BASE = BASE + 0x1000
COMMAND_QWORDS = 26
COMMAND_HALFWORDS = COMMAND_QWORDS * 4
INPUT_HALFWORDS = 32
EXPECTED_HALFWORDS = 8
OUTPUT_HALFWORDS = 2048
TARGET = ROOT / 'rtl/ppu/rk_ppu_pool_demo_rom.sv'
FIXTURE_OUT = ROOT / 'tests/ppu_pool_demo_fixture.json'


def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def load() -> tuple[bytes, list[int], list[int]]:
    manifest = json.loads((FIXTURE / 'manifest.json').read_text())
    if manifest['case'] != CASE:
        raise SystemExit('fixture identity mismatch')
    for name, record in manifest['files'].items():
        path = FIXTURE / name
        if path.stat().st_size != record['bytes'] or sha(path) != record['sha256']:
            raise SystemExit(f'fixture file changed: {name}')
    raw = bytearray((FIXTURE / 'regcmd.bin').read_bytes())
    if len(raw) != COMMAND_HALFWORDS * 2:
        raise SystemExit('command stream length changed')
    # Only the two declared relocations are rewritten; the source bytes stay.
    for index, value in ((13, OUTPUT_BASE), (20, INPUT_BASE)):
        offset = index * 8
        raw[offset + 2:offset + 6] = value.to_bytes(4, 'little')
    command = bytes(raw)
    input_bytes = (FIXTURE / 'in.bin').read_bytes()[:INPUT_HALFWORDS * 2]
    if any((FIXTURE / 'in.bin').read_bytes()[INPUT_HALFWORDS * 2:]):
        raise SystemExit('input bytes beyond the 64-byte read window are nonzero')
    device = (FIXTURE / 'device_out.bin').read_bytes()
    if any(device[EXPECTED_HALFWORDS * 2:]):
        raise SystemExit('captured device BO tail is not zero; checker would be wrong')
    expected = list(struct.unpack(f'<{EXPECTED_HALFWORDS}H', device[:16]))
    if (FIXTURE / 'out_init.bin').read_bytes() != bytes(4096):
        raise SystemExit('initial output BO is not all zero')
    return command, [int.from_bytes(input_bytes[i:i+2], 'little')
                     for i in range(0, len(input_bytes), 2)], expected


def render(command: bytes, inputs: list[int], expected: list[int]) -> str:
    command_words = [int.from_bytes(command[i:i+2], 'little')
                     for i in range(0, len(command), 2)]
    text = '''// SPDX-License-Identifier: MIT
`timescale 1ns/1ps
// Generated by tools/ppu/gen_pool_demo.py from the frozen INT8 C16 H2 W2
// capture. Do not edit by hand; run the generator instead.
module rk_ppu_pool_demo_rom (
    input  logic [6:0]  command_index,
    output logic [15:0] command_data,
    input  logic [4:0]  input_index,
    output logic [15:0] input_data,
    input  logic [2:0]  expected_index,
    output logic [15:0] expected_data,
    output logic [31:0] command_base, input_base, output_base,
    output logic [31:0] start_amount
);
    assign command_base = 32'h%08x;
    assign input_base = 32'h%08x;
    assign output_base = 32'h%08x;
    assign start_amount = 32'd%d;
    always_comb begin
        command_data = 16'd0;
        case (command_index)
''' % (COMMAND_BASE, INPUT_BASE, OUTPUT_BASE, COMMAND_QWORDS)
    for index, value in enumerate(command_words):
        text += f"            7'd{index}: command_data = 16'h{value:04x};\n"
    text += '''            default: begin end
        endcase
    end
    always_comb begin
        input_data = 16'd0;
        case (input_index)
'''
    for index, value in enumerate(inputs):
        text += f"            5'd{index}: input_data = 16'h{value:04x};\n"
    text += '''            default: begin end
        endcase
    end
    always_comb begin
        expected_data = 16'd0;
        case (expected_index)
'''
    for index, value in enumerate(expected):
        text += f"            3'd{index}: expected_data = 16'h{value:04x};\n"
    text += '''            default: begin end
        endcase
    end
endmodule
'''
    return text


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    command, inputs, expected = load()
    source = render(command, inputs, expected)
    record = {
        'case': CASE,
        'description': 'Captured signed-INT8 C16 H2 W2 maximum pooling self-test image data.',
        'command_bytes': len(command),
        'command_sha256': hashlib.sha256(command).hexdigest(),
        'input_halfwords': len(inputs),
        'expected_halfwords': len(expected),
        'expected_values': expected,
        'output_halfwords': OUTPUT_HALFWORDS,
        'command_base': COMMAND_BASE,
        'input_base': INPUT_BASE,
        'output_base': OUTPUT_BASE,
    }
    outputs = {TARGET: source,
               FIXTURE_OUT: json.dumps(record, indent=2, sort_keys=True) + '\n'}
    for path, content in outputs.items():
        if args.check:
            if not path.exists() or path.read_text() != content:
                raise SystemExit(f'Generated file is stale: {path}')
        else:
            path.write_text(content)
    print('Pooling demo ROM matches the frozen capture.' if args.check
          else 'Generated captured signed-INT8 pooling demo ROM.')
    return 0


if __name__ == '__main__':
    raise SystemExit(main())
