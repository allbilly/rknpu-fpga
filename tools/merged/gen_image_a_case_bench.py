# The three DMA-address relocations every strict conv runner applies: the frozen
# captures were taken with the device's own BO placement, and the replay stages
# them at plan-time addresses. The indices come from each fixture manifest
# (`address_qwords`), so this is a relocation, never a field rewrite.
BENCH_TEMPLATE = """\
// GENERATED by tools/merged/gen_image_a_case_bench.py for case {case}
//
// PAGE-LEVEL replay bench. In the S1 architecture the page wrapper owns the AXI
// register contract and the engine's memory master, so proving the frozen case
// needs exactly: page AXI slave + engine + a 64 KiB halfword memory model. The
// merged TOP is deliberately not instantiated here: Icarus runs the full top at
// ~17 cycles/s (one case would take 25+ minutes), while the page bench runs the
// same engine workload in a few minutes. The top's wiring is proven separately
// by the page contract (54/54 captured QWORDs) and the merged scaffold bench
// (31 checks per SLVERR hole).
`timescale 1ns/1ps
module tb_image_a_case_replay;
    localparam logic [31:0] REG_ID            = 32'h0;
    localparam logic [31:0] REG_ABI           = 32'h4;
    localparam logic [31:0] REG_STATUS        = 32'h8;
    localparam logic [31:0] REG_COMMAND       = 32'hc;
    localparam logic [31:0] REG_START_ADDRESS = 32'h10;
    localparam logic [31:0] REG_START_AMOUNT  = 32'h14;
    localparam logic [31:0] REG_JOB_TAG       = 32'h18;
    localparam logic [31:0] ID_RKCV           = 32'h524b_4356;
    localparam logic [31:0] ABI              = 32'h0001_0000;
    localparam integer ST_CAN_SUBMIT = 0, ST_ACTIVE = 1, ST_RESULT_VALID = 2,
                       ST_RESULT_ERROR = 3, ST_MEMORY_READY = 4, ST_CORE_ERROR = 5;

    localparam int unsigned CMD_BYTES = {cmd_bytes};
    localparam int unsigned IN_BYTES  = {in_bytes};
    localparam int unsigned W_BYTES   = {w_bytes};
    localparam int unsigned OUT_BYTES = {out_bytes};
    localparam logic [31:0] CMD_ADDR = 32'h{cmd_addr:08x};
    localparam logic [31:0] IN_ADDR  = 32'h{in_addr:08x};
    localparam logic [31:0] W_ADDR   = 32'h{w_addr:08x};
    localparam logic [31:0] OUT_ADDR = 32'h{out_addr:08x};

    logic clk = 1'b0;
    always #10 clk = ~clk;                 // 50 MHz, unchanged
    logic rst_n = 1'b0;

    // ---- page AXI slave -------------------------------------------------
    logic [15:0] awaddr = '0, araddr = '0;
    logic [2:0]  awprot = '0, arprot = '0;
    logic awvalid = 0, arvalid = 0;
    logic [31:0] wdata = '0;
    logic [3:0]  wstrb = 4'hf;
    logic wvalid = 0;
    logic awready, wready, bvalid, bready = 1'b1;
    logic [1:0] bresp;
    logic [31:0] rdata;
    logic [1:0] rresp;
    logic rvalid, rready = 1'b1;

    // ---- page memory master + 64 KiB halfword memory model --------------
    logic mem_req_valid, mem_req_ready, mem_req_write;
    logic [31:0] mem_req_addr;
    logic [15:0] mem_req_wdata;
    logic mem_rsp_valid, mem_rsp_ready, mem_rsp_error;
    logic [15:0] mem_rsp_rdata;
    logic page_busy, page_done, page_error;
    logic [7:0] page_error_code;

    logic [15:0] mem [0:32767];
    logic rsp_pending;
    assign mem_req_ready = 1'b1;
    always @(posedge clk) begin
        if (!rst_n) begin
            rsp_pending <= 0; mem_rsp_valid <= 0; mem_rsp_rdata <= 0;
            mem_rsp_error <= 0;
        end else begin
            mem_rsp_valid <= 0;
            if (mem_req_valid && mem_req_ready && !rsp_pending) begin
                rsp_pending <= 1;
                if (mem_req_write) mem[mem_req_addr[15:1]] <= mem_req_wdata;
                mem_rsp_rdata <= mem[mem_req_addr[15:1]];
            end else if (rsp_pending) begin
                rsp_pending <= 0; mem_rsp_valid <= 1;
            end
        end
    end

    rk_conv_runtime_page_axi dut (
        .clk, .rst_n, .page_cancel(1'b0), .memory_ready(1'b1),
        .s_axil_awaddr(awaddr), .s_axil_awprot(awprot), .s_axil_awvalid(awvalid),
        .s_axil_awready(awready), .s_axil_wdata(wdata), .s_axil_wstrb(wstrb),
        .s_axil_wvalid(wvalid), .s_axil_wready(wready), .s_axil_bresp(bresp),
        .s_axil_bvalid(bvalid), .s_axil_bready(bready), .s_axil_araddr(araddr),
        .s_axil_arprot(arprot), .s_axil_arvalid(arvalid), .s_axil_arready(arready),
        .s_axil_rdata(rdata), .s_axil_rresp(rresp), .s_axil_rvalid(rvalid),
        .s_axil_rready(rready),
        .mem_req_valid, .mem_req_ready, .mem_req_write, .mem_req_addr,
        .mem_req_wdata, .mem_rsp_valid, .mem_rsp_ready, .mem_rsp_rdata,
        .mem_rsp_error,
        .page_busy, .page_done, .page_error, .page_error_code);

    logic [31:0] value;
    integer frames = 0, checks = 0;

    task automatic axil_write(input logic [15:0] addr, input logic [31:0] data);
        begin
            @(negedge clk); awaddr = addr; awprot = '0; awvalid = 1;
            wdata = data; wstrb = 4'hf; wvalid = 1;
            @(posedge clk);
            while (!(awready && wready)) @(posedge clk);
            @(negedge clk); awvalid = 0; wvalid = 0;
            while (!bvalid) @(posedge clk);
            @(posedge clk); checks = checks + 1;
        end
    endtask

    task automatic axil_read(input logic [15:0] addr, output logic [31:0] data);
        begin
            @(negedge clk); araddr = addr; arprot = '0; arvalid = 1;
            @(posedge clk);
            while (!arready) @(posedge clk);
            @(negedge clk); arvalid = 0;
            while (!rvalid) @(posedge clk);
            data = rdata; checks = checks + 1;
            @(posedge clk);
        end
    endtask

    // Fixture images (16-bit little-endian words) and their addresses.
    logic [15:0] cmd_img  [0:{cmd_words_minus1}];
    logic [15:0] in_img   [0:{in_words_minus1}];
    logic [15:0] w_img    [0:{w_words_minus1}];
    logic [15:0] gold_img [0:{out_words_minus1}];

    integer i, w, errors, fd;
    logic [31:0] status;
    logic [15:0] expected_hw;
    logic [31:0] addr;

    initial begin : TEST
        errors = 0; checks = 0;
        $readmemh("{cmd_hex}", cmd_img);
        $readmemh("{in_hex}", in_img);
        $readmemh("{w_hex}", w_img);
        $readmemh("{gold_hex}", gold_img);

        // Preload the window: the host's buffer load is staging, not the contract
        // (the identical bytes are what the strict replays stage too).
        for (w = 0; w < CMD_BYTES / 2; w = w + 1)
            mem[(CMD_ADDR - 32'h0) / 2 + w] = cmd_img[w];
        for (w = 0; w < IN_BYTES / 2; w = w + 1)
            mem[(IN_ADDR - 32'h0) / 2 + w] = in_img[w];
        for (w = 0; w < W_BYTES / 2; w = w + 1)
            mem[(W_ADDR - 32'h0) / 2 + w] = w_img[w];
        // Canary fill the whole output BO first (same pattern the strict runners
        // use), so "not written" is distinguishable from "written zero".
        for (w = 0; w < OUT_BYTES / 2; w = w + 1)
            mem[(OUT_ADDR - 32'h0) / 2 + w] = 16'ha5a5 ^ w[15:0];
        repeat (8) @(posedge clk);
        @(negedge clk); rst_n = 1'b1;
        repeat (8) @(posedge clk);

        axil_read(16'h0000, value);
        if (value !== ID_RKCV) begin
            $display("FAIL {case}: identity=%08x", value); errors = errors + 1;
        end
        axil_read(16'h0004, value);
        if (value !== ABI) begin
            $display("FAIL {case}: abi=%08x", value); errors = errors + 1;
        end
        axil_read(16'h0008, status);
        if (status[ST_MEMORY_READY] !== 1'b1) begin
            $display("FAIL {case}: status=%08x memory_ready=0", status);
            errors = errors + 1;
        end

{relocations}
        axil_write(16'h0010, CMD_ADDR);
        axil_write(16'h0014, CMD_BYTES / 8);
        axil_write(16'h0018, 32'hCA5E{tag});
        axil_write(16'h000c, 32'h1);              // CMD_SUBMIT

        // Poll STATUS until the page stops working. A page AXI read costs a
        // handful of memory cycles (no 640-cycle mailbox frame), so a dense
        // ladder finishes as soon as the job does instead of sleeping through a
        // fixed interval and idling to the watchdog (which cost ~10 minutes per
        // case with the original fixed waits).
        i = 0;
        axil_read(16'h0008, status);
        $display("STATUS after submit: %08x (active=%b valid=%b err=%b)",
                 status, status[ST_ACTIVE], status[ST_RESULT_VALID],
                 status[ST_RESULT_ERROR]);
        while (status[ST_ACTIVE] === 1'b1 && status[ST_RESULT_VALID] !== 1'b1 &&
               status[ST_RESULT_ERROR] !== 1'b1 && i < 40000) begin
            #5000;                       // 5 us: ample for a STATUS round trip
            axil_read(16'h0008, status);
            i = i + 1;
        end
        // One more read in case a job finished between polls.
        if (status[ST_RESULT_VALID] !== 1'b1 && status[ST_RESULT_ERROR] !== 1'b1) begin
            axil_read(16'h0008, status);
        end
        if (status[ST_CORE_ERROR] === 1'b1 || status[ST_RESULT_ERROR] === 1'b1) begin
            $display("FAIL {case}: page faulted status=%08x code=%0d",
                     status, status[23:16]);
            errors = errors + 1;
        end
        if (status[ST_RESULT_VALID] !== 1'b1) begin
            $display("FAIL {case}: no result valid (status=%08x)", status);
            errors = errors + 1;
        end

        // Dump the complete runtime output region; the comparison against the
        // frozen capture is done in Python using the SAME rule as the proven
        // leg A/B harness. Comparing the raw device BO here would be wrong: the
        // vendor captures carry arbitrary values in the padded OC lanes, while
        // the engine contract writes zeros there (see the runner's
        // compare_output docstring in tests/conv/runtime/run_runtime_equiv.py).
        $display("STATUS final: %08x (valid=%b err=%b) out_word0=%04x out_word1=%04x",
                 status, status[ST_RESULT_VALID], status[ST_RESULT_ERROR],
                 mem[(OUT_ADDR - 32'h0) / 2], mem[(OUT_ADDR - 32'h0) / 2 + 1]);
        fd = $fopen("{out_dump}", "w");
        for (i = 0; i < OUT_BYTES / 2; i = i + 1)
            $fdisplay(fd, "%04x", mem[(OUT_ADDR - 32'h0) / 2 + i]);
        $fclose(fd);
        checks = checks + 1;

        if (errors == 0)
            $display("PASS IMAGE_A_CASE {case} dump_words=%0d checks=%0d",
                     OUT_BYTES / 2, checks);
        else
            $display("FAIL IMAGE_A_CASE {case} errors=%0d", errors);
        $finish;
    end

    initial begin
        #250_000_000;   // 250 ms: generous for the largest frozen shape
        $display("FAIL {case}: watchdog at %0t checks=%0d", $time, checks);
        $finish;
    end
endmodule
"""
def sha(path: Path) -> str:
    return hashlib.sha256(path.read_bytes()).hexdigest()


def write_hex(directory: Path, name: str, path: Path) -> tuple[str, int]:
    """Convert a .bin BO to a little-endian 16-bit word hex image."""
    data = path.read_bytes()
    words = [int.from_bytes(data[i:i + 2], 'little')
             for i in range(0, len(data) - 1, 2)]
    text = ''
    for index, word in enumerate(words):
        text += f'{word:04x}'
        text += '\n' if (index % 32 == 31) or index == len(words) - 1 else ' '
    (directory / name).write_text(text)
    return name, len(words)


def relocations_text(case: dict, planned: dict) -> str:
    """The three DMA-address relocations, exactly as the strict runners do them.

    `tools/conv/run_conv_simple_axi.py` patches ``raw[offset+2 : offset+6]`` with
    the new BO address, i.e. the 32-bit pointer occupies the SECOND halfword pair
    of each relocation QWORD. Patching the QWORD's base word instead would
    overwrite the opcode/field bytes, and the decoder then rejects the job with
    code 4 (buffer gate) — which is exactly what the first version of this bench
    did.
    """
    addresses = {'input': planned['input']['address'],
                 'weight': planned['weight']['address'],
                 'output': planned['output']['address']}
    # The frozen manifests record the order as (input, weight, output).
    targets = ['input', 'weight', 'output']
    lines = []
    for index, name in zip(case['address_qwords'], targets):
        # Byte offset inside the command BO, plus the +2 that the strict runners
        # use within the QWORD.
        byte_offset = index * 8 + 2
        halfword = byte_offset // 2
        value = addresses[name]
        lines.append(
            f"        mem[CMD_ADDR / 2 + 32'd{halfword}] = 16'h{value & 0xffff:04x};"
            f"   // {name} BO pointer, low halfword")
        lines.append(
            f"        mem[CMD_ADDR / 2 + 32'd{halfword + 1}] = 16'h{(value >> 16) & 0xffff:04x};"
            f"   // {name} BO pointer, high halfword")
    return '\n'.join(lines) if lines else '        // no relocations recorded'


def build_bench(case: dict, planned: dict, fixture: Path, directory: Path) -> Path:
    cmd_words, in_words = write_hex(directory, 'cmd.hex',
                                    fixture / 'regcmd.bin')[1], 0
    in_name = case['input_file']
    w_name = case['weight_file']
    in_path = fixture / ({
        'input.bin': 'input.bin', 'a.bin': 'a.bin'}[in_name])
    w_path = fixture / ({'weight.bin': 'weight.bin', 'w.bin': 'w.bin'}[w_name])
    in_words = write_hex(directory, 'in.hex', in_path)[1]
    w_words = write_hex(directory, 'w.hex', w_path)[1]
    out_words = write_hex(directory, 'gold.hex',
                          fixture / case['expected_file'])[1]
    max_words = max(cmd_words, in_words, w_words, out_words)

    text = BENCH_TEMPLATE.format(
        case=case['case'],
        cmd_bytes=planned['command']['bytes'],
        in_bytes=planned['input']['bytes'],
        w_bytes=planned['weight']['bytes'],
        out_bytes=planned['output']['bytes'],
        cmd_addr=planned['command']['address'],
        in_addr=planned['input']['address'],
        w_addr=planned['weight']['address'],
        out_addr=planned['output']['address'],
        cmd_words=cmd_words, in_words=in_words, w_words=w_words,
        out_words=out_words, max_words=max_words,
        cmd_words_minus1=cmd_words - 1, in_words_minus1=in_words - 1,
        w_words_minus1=w_words - 1, out_words_minus1=out_words - 1,
        tag=f"{int(hashlib.sha256(case['case'].encode()).hexdigest()[:8], 16) & 0xffff:04x}",
        out_dump=str(directory / 'runtime_out.hex'),
        cmd_hex=str(directory / 'cmd.hex'),
        in_hex=str(directory / 'in.hex'),
        w_hex=str(directory / 'w.hex'),
        gold_hex=str(directory / 'gold.hex'),
        relocations=relocations_text(case, planned))
    bench = directory / 'tb_image_a_case_replay.sv'
    bench.write_text(text)
    return bench


