#!/usr/bin/env python3
"""Generate + run the Image-A S1 per-case family replay bench.

For every frozen conv fixture in the replay plan this tool:

1. stages the fixture's command QWORD stream and operand BOs into the 64 KiB
   Image-A window (using the THREE documented DMA-address relocations the strict
   runners also apply), through the frozen USER2 mailbox -> AXI bridge path;
2. programs START_ADDRESS / START_AMOUNT and submits the job to the real
   runtime page;
3. polls STATUS until the page reports done/error;
4. reads back the COMPLETE output BO over the same AXI path and compares it
   byte-exactly with the fixture's captured device output.

The bench is generated with the fixture bytes baked in (Icarus `$readmemh`), so
one bench == one case and a failure is attributable to that case alone.

Evidence rules: run only through `build/verif/host_guard/safe_run.sh`, record
source hashes before/after, never treat a guard kill as a PASS, and never
weaken the comparison (complete BO, byte exact, no tolerance).
"""
