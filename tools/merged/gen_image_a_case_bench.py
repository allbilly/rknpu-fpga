def compare_runtime_output(case: dict, directory: Path) -> tuple[bool, str]:
    """Compare the dumped runtime region using the proven leg A/B rule.

    For the vendor FP16 family the device BO carries arbitrary values in the
    padded OC lanes while the engine contract writes zeros there, so the oracle
    is: defined NCHW values from `expected.bin` (transposed per atom) plus zeros
    in the padded lanes. That is exactly what
    `tests/conv/runtime/run_runtime_equiv.py::compare_output` does, and reusing
    its rule keeps this replay consistent with the hash-bound equivalence
    receipts rather than inventing a second oracle.
    """
    import struct
    manifest = json.loads((ROOT / case['directory'] / 'manifest.json').read_text())
    shape = manifest.get('shape') or {}
    if isinstance(shape, str):
        # Legacy manifests encode the shape as "b1_c4_h9_w9_oc4_wic4_k3x3_g1".
        import re as _re
        tokens = dict(_re.findall(r'([a-z]+)(\d+)', shape))
        kernel = _re.findall(r'k(\d+)x(\d+)', shape)
        shape = dict(batch=int(tokens.get('b', 1)),
                     input_channels=int(tokens.get('c', 0)),
                     input_height=int(tokens.get('h', 0)),
                     input_width=int(tokens.get('w', 0)),
                     output_channels=int(tokens.get('oc', 0)),
                     weight_input_channels=int(tokens.get('wic', 0)),
                     groups=int(tokens.get('g', 1)),
                     kernel=[int(kernel[0][0]), int(kernel[0][1])] if kernel else [3, 3],
                     padding='valid', stride=[1, 1])
    dump_path = directory / 'runtime_out.hex'
    if not dump_path.is_file():
        return False, 'bench produced no runtime_out.hex'
    runtime = [int(v, 16) for v in dump_path.read_text().split()]
    fixture = ROOT / case['directory']
    expected_path = fixture / 'expected.bin'
    device_path = fixture / case['expected_file']
    device = struct.unpack(f'<{device_path.stat().st_size // 2}H',
                           device_path.read_bytes())
    expected = struct.unpack(f'<{expected_path.stat().st_size // 2}H',
                             expected_path.read_bytes())

    # Output geometry: the engine writes (atoms * 8) halfwords, where each atom
    # carries 8 OC lanes (out_c real + zero padding).
    # Two frozen manifest generations carry the geometry under different keys:
    # the vendor family uses output_channels/output_height/output_width, the
    # conv-simple family uses out_c/in_h/in_w plus kernel/stride (so the output
    # height/width are derived).
    out_c = int(shape.get('output_channels') or shape.get('out_c') or 0)
    out_h = int(shape.get('output_height') or 0)
    out_w = int(shape.get('output_width') or 0)
    if out_c > 0 and not (out_h and out_w):
        kh = shape.get('kh') or (shape.get('kernel') or [0])[0]
        kw = shape.get('kw') or (shape.get('kernel') or [0, 0])[1]
        stride = shape.get('stride') or 1
        stride_h = stride[0] if isinstance(stride, (list, tuple)) else stride
        stride_w = stride[1] if isinstance(stride, (list, tuple)) else stride
        pad = 0 if str(shape.get('padding', 'valid')) == 'valid' else 1
        in_h = int(shape.get('in_h') or shape.get('input_height') or 0)
        in_w = int(shape.get('in_w') or shape.get('input_width') or 0)
        out_h = (in_h + 2 * pad - kh) // stride_h + 1
        out_w = (in_w + 2 * pad - kw) // stride_w + 1
    if out_c <= 0 or out_h <= 0 or out_w <= 0:
        return False, 'manifest has no usable output geometry'
    atoms = out_h * out_w
    written = atoms * 8
    if len(runtime) < written:
        return False, f'runtime dump has {len(runtime)} words, need {written}'

    mismatches = 0
    first = None
    integrity = 0
    for atom in range(atoms):
        for lane in range(8):
            idx = atom * 8 + lane
            got = runtime[idx]
            if lane < out_c:
                want = expected[lane * atoms + atom]
                if idx < len(device) and device[idx] != want:
                    integrity += 1
                if got != want:
                    mismatches += 1
                    first = first or ('expected', idx, got, want)
            else:
                if got != 0:
                    mismatches += 1
                    first = first or ('padding', idx, got, 0)
    detail = (f'atoms={atoms} out_c={out_c} written={written} '
              f'mismatches={mismatches} fixture_integrity_mismatches={integrity} '
              f'first={first}')
    return (mismatches == 0 and integrity == 0), detail


def compile_and_run(bench: Path, directory: Path, hole: int = 0) -> tuple[bool, str]:
    sources = [str(ROOT / name) for name in PAGE_SOURCES]
    binary = directory / 'case.vvp'
    argv = [shutil.which('iverilog'), '-g2012', '-Itests', '-Irtl/vendor/nvdla',
            '-DDESIGNWARE_NOEXIST', '-o', str(binary),
            '-s', 'tb_image_a_case_replay'] + sources + [str(bench)]
    compiled = subprocess.run(argv, cwd=ROOT, capture_output=True, text=True,
                              timeout=300)
    if compiled.returncode != 0:
        return False, 'compile failed:\n' + (compiled.stdout + compiled.stderr)[-3000:]
    ran = subprocess.run([shutil.which('vvp'), str(binary)], cwd=ROOT,
                         capture_output=True, text=True, timeout=1800)
    output = ran.stdout + ran.stderr
    ok = ran.returncode == 0 and PASS_MARK in output
    return ok, output[-3000:]


def guarded_kill() -> bool:
    if not GUARD_LOG.is_file():
        return False
    lines = GUARD_LOG.read_text(errors='ignore').splitlines()[-120:]
    return any('GUARD_KILL' in line and ('vvp' in line or 'iverilog' in line)
               for line in lines)


def fixture_staging(case: dict) -> dict:
    """Stage BOs at the fixture's OWN recorded addresses.

    The frozen manifest records the device's BO placement (`command.addresses` /
    `command_stream.addresses`, defaulting to 0x1000/0x2000/0x3000 for the vendor
    family). Staging them there is what the proven leg A/B harness does, and it
    guarantees the decoder's non-overlap / 16-byte-alignment gate can pass. The
    command stream is placed at window offset 0 so the wrapper's START_ADDRESS is
    trivially valid.
    """
    manifest = json.loads((ROOT / case['directory'] / 'manifest.json').read_text())
    stream = manifest.get('command_stream') or manifest.get('command') or {}
    addresses = stream.get('addresses') or {}
    in_addr = addresses.get('a', addresses.get('input')) or 0x1000
    w_addr = addresses.get('w', addresses.get('weight')) or 0x2000
    out_addr = addresses.get('out') or 0x3000
    return dict(command=dict(address=0, bytes=case['files']['regcmd.bin']['bytes']),
                input=dict(address=in_addr, bytes=case['files'][case['input_file']]['bytes']),
                weight=dict(address=w_addr, bytes=case['files'][case['weight_file']]['bytes']),
                output=dict(address=out_addr, bytes=case['files'][case['expected_file']]['bytes']),
                task=dict(address=0, bytes=0))


def main() -> int:
    parser = argparse.ArgumentParser(
        description='Generate and run the Image-A S1 per-case family replay.')
    parser.add_argument('--case', action='append', default=None,
                        help='case name (repeatable); default: every planned case')
    parser.add_argument('--out', type=Path, default=None)
    parser.add_argument('--limit', type=int, default=None,
                        help='stop after this many cases (batching for a warm host)')
    args = parser.parse_args()

    fixtures = {case['case']: case for case in replay.discover_fixtures()}
    cases = args.case or list(fixtures)
    unknown = [name for name in cases if name not in fixtures]
    if unknown:
        print(f'unknown cases: {unknown}', file=sys.stderr)
        return 2

    directory = args.out or (OUT_ROOT /
                             f's1-cases-{time.strftime("%Y%m%dT%H%M%SZ", time.gmtime())}')
    directory = Path(directory)
    if not directory.is_absolute():
        directory = ROOT / directory
    if not directory.resolve().is_relative_to((ROOT / 'build').resolve()):
        print('output must be below build/', file=sys.stderr)
        return 2
    directory.mkdir(parents=True, exist_ok=False)

    results = []
    for name in cases[:args.limit] if args.limit else cases:
        case = fixtures[name]
        planned = fixture_staging(case)
        if replay.plan_case(case)['problems']:
            results.append(dict(case=name, status='FAIL',
                                detail=replay.plan_case(case)['problems']))
            continue
        case_dir = directory / name
        case_dir.mkdir()
        bench = build_bench(case, planned, ROOT / case['directory'], case_dir)
        ran_ok, log = compile_and_run(bench, case_dir)
        if ran_ok:
            cmp_ok, cmp_detail = compare_runtime_output(case, case_dir)
            ok = cmp_ok
            log = log + '\n' + cmp_detail
        else:
            ok = False
        status = 'PASS' if ok else ('BLOCKED-BY-HOST-THERMAL'
                                    if guarded_kill() else 'FAIL')
        results.append(dict(case=name, status=status,
                            command_sha=case['files']['regcmd.bin']['sha256'],
                            expected_sha=case['files'][case['expected_file']]['sha256'],
                            staging=planned, log=log[-900:]))
        print(f'{status} {name}')
        if not ok:
            print(log[-700:])

    payload = dict(cases=results,
                   note='complete output BO byte-exact vs the frozen capture, through '
                        'the real runtime page and the merged-image mailbox path',
                   hardware_accessed=False, vivado_executed=False)
    ok_all = all(r['status'] == 'PASS' for r in results)
    record = dict(schema='rk3588-image-a-s1-cases/v1',
                  status='PASS' if ok_all else 'FAIL',
                  generated_utc=time.strftime('%Y-%m-%dT%H:%M:%SZ', time.gmtime()),
                  source_hashes={str(p.relative_to(ROOT)): sha(p)
                                 for p in sorted({
                                     ROOT / 'tools/merged/gen_image_a_case_bench.py',
                                     ROOT / 'tools/merged/run_image_a_replay.py',
                                     ROOT / 'tools/merged/vivado_merged_image.py',
                                     ROOT / 'fpga/merged/merged_sources.json',
                                     ROOT / 'fpga/ypcb_merged_top.sv',
                                     ROOT / 'rtl/cmac/experimental/runtime/rk_conv_runtime_page_axi.sv',
                                     ROOT / replay.STUBS})},
                  payload=payload)
    (directory / 'report.json').write_text(json.dumps(record, indent=2, sort_keys=True) + '\n')
    passed = sum(1 for r in results if r['status'] == 'PASS')
    print(f'\nS1 family replay: {passed}/{len(results)} PASS  -> {directory}/report.json')
    return 0 if ok_all else 1


if __name__ == '__main__':
    raise SystemExit(main())
