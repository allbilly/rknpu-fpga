`timescale 1ns/1ps
// Mechanical dual-host composition around the unchanged raw DDR backend.
// JTAG and PCIe use the backend's retained c0 client epoch. Link-health inputs
// must already be synchronized into c0_ui_clk; link reset must not reset this
// frontend independently of c0_clients_rst_n.
module rk_dual_host_ddr #(
    parameter logic [31:0] BASE = 0,
    parameter logic [32:0] BYTES = 33'h080000000,
    parameter int unsigned TIMEOUT_CYCLES = 65536,
    parameter int unsigned MAX_TASKS = 4095,
    parameter int unsigned SYS_HOLD_CYCLES = 64,
    parameter int unsigned UI_FRESH_CYCLES = 4,
    parameter int unsigned SYNC_STAGES = 3,
    parameter int unsigned RESET_WAIT_TIMEOUT_CYCLES = 65536
) (
    input logic sys_clk, cfg_reset, reset_req_valid,
    output logic reset_req_ready,
    input logic c0_ui_clk, c1_ui_clk, c0_ui_clk_sync_rst, c1_ui_clk_sync_rst,
    input logic c0_init_calib_complete, c0_interrupt,
    output logic mig_sys_rst_n, sys_clients_rst_n, c0_clients_rst_n, c1_clients_rst_n,
    output logic c0_aresetn, c1_aresetn,
    output logic sequence_busy, sequence_complete, admission_blocked, sequence_fault,
    output logic [7:0] sequence_fault_code,
    input logic req_valid,
    output logic req_ready,
    input logic [603:0] req,
    output logic rsp_valid,
    output logic [511:0] rsp_data,
    output logic [7:0] rsp_status,
    output logic [15:0] rsp_seq,
    input logic jtag_link_healthy, pcie_link_healthy,
    output logic [1:0] transport_owner,
    output logic [31:0] transport_lease_epoch,
    output logic transport_release_ready,
    output logic pcie_irq, pcie_protocol_fault, pcie_epoch_fault, owner_protocol_fault,
    output logic [7:0] owner_failure_code,
    output logic irq, fault,
    output logic [7:0] fault_code,
    output logic init_complete, init_active, memory_ready, job_owned, job_active, job_retired,

    input logic [31:0] pcie_axil_awaddr,
    input logic [2:0] pcie_axil_awprot,
    input logic pcie_axil_awvalid,
    output logic pcie_axil_awready,
    input logic [31:0] pcie_axil_wdata,
    input logic [3:0] pcie_axil_wstrb,
    input logic pcie_axil_wvalid,
    output logic pcie_axil_wready,
    output logic [1:0] pcie_axil_bresp,
    output logic pcie_axil_bvalid,
    input logic pcie_axil_bready,
    input logic [31:0] pcie_axil_araddr,
    input logic [2:0] pcie_axil_arprot,
    input logic pcie_axil_arvalid,
    output logic pcie_axil_arready,
    output logic [31:0] pcie_axil_rdata,
    output logic [1:0] pcie_axil_rresp,
    output logic pcie_axil_rvalid,
    input logic pcie_axil_rready,

    output logic [3:0] m_axi_awid, m_axi_arid,
    output logic [30:0] m_axi_awaddr, m_axi_araddr,
    output logic [7:0] m_axi_awlen, m_axi_arlen,
    output logic [2:0] m_axi_awsize, m_axi_arsize,
    output logic [1:0] m_axi_awburst, m_axi_arburst,
    output logic m_axi_awlock, m_axi_arlock,
    output logic [3:0] m_axi_awcache, m_axi_arcache,
    output logic [2:0] m_axi_awprot, m_axi_arprot,
    output logic [3:0] m_axi_awqos, m_axi_arqos,
    output logic m_axi_awvalid,
    input logic m_axi_awready,
    output logic [511:0] m_axi_wdata,
    output logic [63:0] m_axi_wstrb,
    output logic m_axi_wlast, m_axi_wvalid,
    input logic m_axi_wready,
    input logic [3:0] m_axi_bid,
    input logic [1:0] m_axi_bresp,
    input logic m_axi_bvalid,
    output logic m_axi_bready,
    output logic m_axi_arvalid,
    input logic m_axi_arready,
    input logic [3:0] m_axi_rid,
    input logic [511:0] m_axi_rdata,
    input logic [1:0] m_axi_rresp,
    input logic m_axi_rlast, m_axi_rvalid,
    output logic m_axi_rready,
    output logic [31:0] m_axi_ctrl_awaddr,
    output logic m_axi_ctrl_awvalid,
    input logic m_axi_ctrl_awready,
    output logic [31:0] m_axi_ctrl_wdata,
    output logic m_axi_ctrl_wvalid,
    input logic m_axi_ctrl_wready,
    input logic [1:0] m_axi_ctrl_bresp,
    input logic m_axi_ctrl_bvalid,
    output logic m_axi_ctrl_bready,
    output logic [31:0] m_axi_ctrl_araddr,
    output logic m_axi_ctrl_arvalid,
    input logic m_axi_ctrl_arready,
    input logic [31:0] m_axi_ctrl_rdata,
    input logic [1:0] m_axi_ctrl_rresp,
    input logic m_axi_ctrl_rvalid,
    output logic m_axi_ctrl_rready
);
    logic core_req_valid, core_req_ready, core_rsp_valid;
    logic [603:0] core_req;
    logic [511:0] core_rsp_data;
    logic [7:0] core_rsp_status;
    logic [15:0] core_rsp_seq;

    rk_pcie_jtag_frame_frontend frontend (
        .clk(c0_ui_clk), .rst_n(c0_clients_rst_n),
        .release_ready(transport_release_ready),
        .jtag_link_healthy(jtag_link_healthy), .pcie_link_healthy(pcie_link_healthy),
        .s_axil_awaddr(pcie_axil_awaddr), .s_axil_awprot(pcie_axil_awprot),
        .s_axil_awvalid(pcie_axil_awvalid), .s_axil_awready(pcie_axil_awready),
        .s_axil_wdata(pcie_axil_wdata), .s_axil_wstrb(pcie_axil_wstrb),
        .s_axil_wvalid(pcie_axil_wvalid), .s_axil_wready(pcie_axil_wready),
        .s_axil_bresp(pcie_axil_bresp), .s_axil_bvalid(pcie_axil_bvalid),
        .s_axil_bready(pcie_axil_bready), .s_axil_araddr(pcie_axil_araddr),
        .s_axil_arprot(pcie_axil_arprot), .s_axil_arvalid(pcie_axil_arvalid),
        .s_axil_arready(pcie_axil_arready), .s_axil_rdata(pcie_axil_rdata),
        .s_axil_rresp(pcie_axil_rresp), .s_axil_rvalid(pcie_axil_rvalid),
        .s_axil_rready(pcie_axil_rready),
        .jtag_req_valid(req_valid), .jtag_req_ready(req_ready), .jtag_req(req),
        .jtag_rsp_valid(rsp_valid), .jtag_rsp_data(rsp_data),
        .jtag_rsp_status(rsp_status), .jtag_rsp_seq(rsp_seq),
        .m_req_valid(core_req_valid), .m_req_ready(core_req_ready), .m_req(core_req),
        .m_rsp_valid(core_rsp_valid), .m_rsp_data(core_rsp_data),
        .m_rsp_status(core_rsp_status), .m_rsp_seq(core_rsp_seq),
        .owner(transport_owner), .lease_epoch(transport_lease_epoch),
        .pcie_irq(frontend_irq), .pcie_protocol_fault(pcie_protocol_fault), .pcie_epoch_fault(pcie_epoch_fault),
        .owner_protocol_fault(owner_protocol_fault), .owner_failure_code(owner_failure_code)
    );
    logic frontend_irq;
    assign pcie_irq = frontend_irq || ((transport_owner == 2'd2) && irq);

    rk_jtag_dual_ddr_async #(
        .BASE(BASE), .BYTES(BYTES), .TIMEOUT_CYCLES(TIMEOUT_CYCLES),
        .MAX_TASKS(MAX_TASKS), .SYS_HOLD_CYCLES(SYS_HOLD_CYCLES),
        .UI_FRESH_CYCLES(UI_FRESH_CYCLES), .SYNC_STAGES(SYNC_STAGES),
        .RESET_WAIT_TIMEOUT_CYCLES(RESET_WAIT_TIMEOUT_CYCLES)
    ) backend (
        .sys_clk(sys_clk), .cfg_reset(cfg_reset), .reset_req_valid(reset_req_valid),
        .reset_req_ready(reset_req_ready), .c0_ui_clk(c0_ui_clk), .c1_ui_clk(c1_ui_clk),
        .c0_ui_clk_sync_rst(c0_ui_clk_sync_rst), .c1_ui_clk_sync_rst(c1_ui_clk_sync_rst),
        .c0_init_calib_complete(c0_init_calib_complete), .c0_interrupt(c0_interrupt),
        .mig_sys_rst_n(mig_sys_rst_n), .sys_clients_rst_n(sys_clients_rst_n),
        .c0_clients_rst_n(c0_clients_rst_n), .c1_clients_rst_n(c1_clients_rst_n),
        .c0_aresetn(c0_aresetn), .c1_aresetn(c1_aresetn),
        .sequence_busy(sequence_busy), .sequence_complete(sequence_complete),
        .admission_blocked(admission_blocked), .sequence_fault(sequence_fault),
        .sequence_fault_code(sequence_fault_code),
        .req_valid(core_req_valid), .req_ready(core_req_ready), .req(core_req),
        .rsp_valid(core_rsp_valid), .rsp_data(core_rsp_data),
        .rsp_status(core_rsp_status), .rsp_seq(core_rsp_seq),
        .irq(irq), .fault(fault), .transport_release_ready(transport_release_ready),
        .fault_code(fault_code), .init_complete(init_complete), .init_active(init_active),
        .memory_ready(memory_ready), .job_owned(job_owned), .job_active(job_active),
        .job_retired(job_retired),
        .m_axi_awid(m_axi_awid), .m_axi_arid(m_axi_arid), .m_axi_awaddr(m_axi_awaddr),
        .m_axi_araddr(m_axi_araddr), .m_axi_awlen(m_axi_awlen), .m_axi_arlen(m_axi_arlen),
        .m_axi_awsize(m_axi_awsize), .m_axi_arsize(m_axi_arsize),
        .m_axi_awburst(m_axi_awburst), .m_axi_arburst(m_axi_arburst),
        .m_axi_awlock(m_axi_awlock), .m_axi_arlock(m_axi_arlock),
        .m_axi_awcache(m_axi_awcache), .m_axi_arcache(m_axi_arcache),
        .m_axi_awprot(m_axi_awprot), .m_axi_arprot(m_axi_arprot),
        .m_axi_awqos(m_axi_awqos), .m_axi_arqos(m_axi_arqos),
        .m_axi_awvalid(m_axi_awvalid), .m_axi_awready(m_axi_awready),
        .m_axi_wdata(m_axi_wdata), .m_axi_wstrb(m_axi_wstrb), .m_axi_wlast(m_axi_wlast),
        .m_axi_wvalid(m_axi_wvalid), .m_axi_wready(m_axi_wready),
        .m_axi_bid(m_axi_bid), .m_axi_bresp(m_axi_bresp), .m_axi_bvalid(m_axi_bvalid),
        .m_axi_bready(m_axi_bready), .m_axi_arvalid(m_axi_arvalid),
        .m_axi_arready(m_axi_arready), .m_axi_rid(m_axi_rid), .m_axi_rdata(m_axi_rdata),
        .m_axi_rresp(m_axi_rresp), .m_axi_rlast(m_axi_rlast), .m_axi_rvalid(m_axi_rvalid),
        .m_axi_rready(m_axi_rready), .m_axi_ctrl_awaddr(m_axi_ctrl_awaddr),
        .m_axi_ctrl_awvalid(m_axi_ctrl_awvalid), .m_axi_ctrl_awready(m_axi_ctrl_awready),
        .m_axi_ctrl_wdata(m_axi_ctrl_wdata), .m_axi_ctrl_wvalid(m_axi_ctrl_wvalid),
        .m_axi_ctrl_wready(m_axi_ctrl_wready), .m_axi_ctrl_bresp(m_axi_ctrl_bresp),
        .m_axi_ctrl_bvalid(m_axi_ctrl_bvalid), .m_axi_ctrl_bready(m_axi_ctrl_bready),
        .m_axi_ctrl_araddr(m_axi_ctrl_araddr), .m_axi_ctrl_arvalid(m_axi_ctrl_arvalid),
        .m_axi_ctrl_arready(m_axi_ctrl_arready), .m_axi_ctrl_rdata(m_axi_ctrl_rdata),
        .m_axi_ctrl_rresp(m_axi_ctrl_rresp), .m_axi_ctrl_rvalid(m_axi_ctrl_rvalid),
        .m_axi_ctrl_rready(m_axi_ctrl_rready)
    );
endmodule
