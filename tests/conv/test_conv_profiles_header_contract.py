#!/usr/bin/env python3
"""Contract checks for the generated exact-profile register template header."""
from __future__ import annotations

import importlib.util
from pathlib import Path
import struct
import unittest

ROOT = Path(__file__).resolve().parents[2]
GENERATOR = ROOT / 'tools/conv/gen_conv_profiles.py'
HEADER = ROOT / 'rtl/cmac/rk_conv_3x3_profiles.svh'


def load_generator():
    spec = importlib.util.spec_from_file_location('gen_conv_profiles', GENERATOR)
    module = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    return module


class GeneratedProfileHeaderTests(unittest.TestCase):
    def test_header_is_current(self) -> None:
        generator = load_generator()
        text = HEADER.read_text()
        self.assertIn('GENERATED by tools/conv/gen_conv_profiles.py', text)
        self.assertEqual(text, generator.emitted(),
                         'header drifted from the pinned fixtures')

    def test_tables_match_the_captured_streams_and_zero_relocations(self) -> None:
        generator = load_generator()
        text = HEADER.read_text()
        relocations = set(generator.ADDRESS_WORDS)
        for profile in generator.PROFILES:
            captured = generator.relocate(profile['case'], profile['addresses'])
            words = struct.unpack('<54Q', captured)
            block = text.split(f"        {profile['id']}: case (index)")[1]
            block = block.split('        endcase')[0]
            for index, word in enumerate(words):
                row = [line for line in block.splitlines()
                       if line.strip().startswith(f'{index}:')][0]
                emitted = int(row.rsplit("64'h", 1)[1].rstrip(';'), 16)
                if index in relocations:
                    # Value field is a runtime relocation, not a constant.
                    self.assertEqual(emitted & ~(0xFFFFFFFF << 16),
                                     word & ~(0xFFFFFFFF << 16),
                                     (profile['case'], index))
                    self.assertEqual((emitted >> 16) & 0xFFFFFFFF, 0,
                                     (profile['case'], index))
                else:
                    self.assertEqual(emitted, word,
                                     (profile['case'], index))

    def test_every_declared_profile_id_is_unique_and_covered(self) -> None:
        generator = load_generator()
        text = HEADER.read_text()
        ids = [p['id'] for p in generator.PROFILES]
        self.assertEqual(sorted(ids), list(range(len(ids))))
        for profile in generator.PROFILES:
            self.assertIn(f"CONV_PROFILE_{profile['name']} = {profile['id']}",
                          text)
            self.assertIn(f"{profile['id']}: case (index)", text)
        self.assertIn('conv_profile_address_word', text)
        self.assertIn('conv_profile_template_word', text)

    def test_generator_rejects_a_case_without_the_declared_relocations(self) -> None:
        generator = load_generator()
        for profile in generator.PROFILES:
            fixture = generator.FIXTURES / profile['case']
            self.assertTrue((fixture / 'manifest.json').is_file(),
                            profile['case'])
            self.assertEqual(len((fixture / 'regcmd.bin').read_bytes()), 54 * 8,
                             profile['case'])


if __name__ == '__main__':
    unittest.main()
