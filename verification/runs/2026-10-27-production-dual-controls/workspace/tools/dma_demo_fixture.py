"""Compile-time ROM fixture from verbatim production SUB(9) BO bytes."""
import json
import struct

from tools.dma_fixtures import production_cases
from model.dma import DMAEmulator
from model.sim import Memory

WINDOWS = ((0x10001000, 0x000, 32), (0x10020000, 0x020, 32),
           (0x10040000, 0x040, 32), (0x10060000, 0x060, 32),
           (0x10061000, 0x080, 32), (0x100e0000, 0x100, 512))


def fixture():
    capture = next(c for c in production_cases() if c['name'] == 'capture_sub_9')
    memory = Memory()
    init = []
    for address, physical, size in WINDOWS:
        assert physical+size <= 4096
        raw = next(data[address-base:address-base+size] for base, data in capture['regions'].items()
                   if base <= address and address+size <= base+len(data))
        memory.map(address, raw)
        init.extend((address+2*i, v) for i, (v,) in enumerate(struct.iter_unpack('<H', raw)))
    emulator = DMAEmulator(memory)
    emulator.submit_dma(capture['address'], capture['amount'])
    assert emulator.completed == 2 and emulator.command_reads == 228 and emulator.memory_transactions == 96
    dst = memory.regions[0x10040000]
    assert dst[:18].hex() == capture['production']['expected_logical_hex']
    expected = [memory.read16(address) for address, _ in init]
    return {'description': 'Verbatim production SUB(9), synthetic inputs/oracle; no RK hardware golden.',
            'capture': capture['name'], 'windows': WINDOWS,
            'start_address': capture['address'], 'start_amount': capture['amount'],
            'tasks': 2, 'command_reads': 228, 'data_transactions': 96,
            'task_sha256': [t['sha256'] for t in capture['production']['tasks']],
            'init': init, 'expected': expected}


def outputs(root):
    f = fixture()
    text = '''// SPDX-License-Identifier: MIT
`timescale 1ns/1ps
// Generated by tools/gen_demo.py from the pinned production BO fixture.
module rk_dma_demo_rom (
    input logic [8:0] index,
    output logic [31:0] address, start_address, start_amount, expected_tasks,
    output logic [15:0] initial_data, expected_data,
    output logic last
);
'''
    text += f"    assign start_address = 32'h{f['start_address']:08x};\n"
    text += f"    assign start_amount = 32'd{f['start_amount']};\n"
    text += f"    assign expected_tasks = 32'd{f['tasks']};\n"
    text += f"    assign last = index == 9'd{len(f['init'])-1};\n"
    text += '    always_comb begin\n        address=0; initial_data=0; expected_data=0;\n        case (index)\n'
    for i, ((address, value), expected) in enumerate(zip(f['init'], f['expected'])):
        text += f"            9'd{i}: begin address=32'h{address:08x}; initial_data=16'h{value:04x}; expected_data=16'h{expected:04x}; end\n"
    text += '            default: begin end\n        endcase\n    end\nendmodule\n'
    return {root/'rtl/rk_dma_demo_rom.sv': text,
            root/'tests/dma_demo_fixture.json': json.dumps(f, indent=2)+'\n'}
