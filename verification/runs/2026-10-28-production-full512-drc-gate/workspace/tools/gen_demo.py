#!/usr/bin/env python3
"""Build deterministic BRAM self-test ROMs; no hardware captures are implied."""
import argparse
import json
from pathlib import Path
import struct
import sys
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from model.half import alu
from model.profile import make_commands
from tools.dma_demo_fixture import outputs as dma_outputs

A, B, D = 0x10000000, 0x10000100, 0x10000200
# Deliberately simple exactly representable inputs, including negative and zero.
AV = [0x3c00, 0x4000, 0x4200, 0xc400, 0x0000, 0x0400, 0x3800, 0x7bff]
BV = [0x4000, 0x4200, 0x4400, 0x3c00, 0x0000, 0x0400, 0x3400, 0xfbff]
ops = ['ADD', 'SUB', 'MUL']
words = [w for op in ops for (w,) in struct.iter_unpack('<Q', make_commands(op,8,A,B,D))]
init = [(A+2*i,v) for i,v in enumerate(AV)] + [(B+2*i,v) for i,v in enumerate(BV)]
init += [(D+2*i,0xdead) for i in range(8)]
expected = [alu(a,b,op) for op in ops for a,b in zip(AV,BV)]
text = '''// SPDX-License-Identifier: MIT
`timescale 1ns/1ps
// Generated by tools/gen_demo.py; fixed smoke-test workload, NOT a driver.
module rk_demo_rom (
    input logic [4:0] init_index,
    input logic [6:0] cmd_index,
    input logic [4:0] check_index,
    output logic [31:0] init_addr,
    output logic [15:0] init_data,
    output logic [63:0] cmd_data,
    output logic [15:0] expected_data
);
    always_comb begin
        init_addr = 0; init_data = 0;
        case (init_index)
'''
for i,(addr,val) in enumerate(init):
    text += f"            5'd{i}: begin init_addr=32'h{addr:08x}; init_data=16'h{val:04x}; end\n"
text += '''            default: begin end
        endcase
        cmd_data = 0;
        case (cmd_index)
'''
for i,w in enumerate(words): text += f"            7'd{i}: cmd_data=64'h{w:016x};\n"
text += '''            default: begin end
        endcase
        expected_data = 0;
        case (check_index)
'''
for i,v in enumerate(expected): text += f"            5'd{i}: expected_data=16'h{v:04x};\n"
text += '''            default: begin end
        endcase
    end
endmodule
'''
fixture = {'description':'Synthetic fixed ADD/SUB/MUL smoke test; not an RK hardware capture.',
           'a':A, 'b':B, 'dst':D, 'input_a_bits':AV, 'input_b_bits':BV,
           'commands':[f'{w:016x}' for w in words], 'expected_bits':expected}
outputs = {ROOT/'rtl/rk_demo_rom.sv':text,
           ROOT/'tests/demo_fixture.json':json.dumps(fixture,indent=2)+'\n'}
outputs.update(dma_outputs(ROOT))
p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
args = p.parse_args()
for path,content in outputs.items():
    if args.check:
        if not path.exists() or path.read_text()!=content:
            raise SystemExit(f'Generated file is stale: {path}')
    else: path.write_text(content)
print('Demo generated files match.' if args.check else 'Generated three-operation BRAM demo ROM.')
